export function translateError(locale: Locale, message: string): string {
  if (locale === "en") return message;
  const exact = bnText[message];
  if (exact) return exact;
  const unreadable = /^A (.+) in that file is unreadable\.$/.exec(message);
  if (unreadable && fileFields[unreadable[1]]) {
    return `এই ফাইলে ${fileFields[unreadable[1]]} পড়া যাচ্ছে না।`;
  }
  const tooLong = /^A (.+) in that file is too long\.$/.exec(message);
  if (tooLong && fileFields[tooLong[1]]) {
    return `এই ফাইলে ${fileFields[tooLong[1]]} অনেক বড়।`;
  }
  return message;
}
