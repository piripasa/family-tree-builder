type Widen<T> = T extends (...args: infer A) => infer R
  ? (...args: A) => Widen<R>
  : T extends readonly (infer U)[]
    ? Widen<U>[]
    : T extends string
      ? string
      : { [K in keyof T]: Widen<T[K]> };

export type Messages = { [K in keyof typeof en]: Widen<(typeof en)[K]> };
